function isValidSudoku(board: string[][]) {
  for (let r = 0; r < 9; r++) {
    const vals = new Set<string>();

    for (let c = 0; c < 9; c++) {
      if (board[r]![c] === ".") continue;
      if (vals.has(board[r]![c]!)) return false;

      vals.add(board[r]![c]!);
    }
  }

  for (let c = 0; c < 9; c++) {
    const vals = new Set<string>();

    for (let r = 0; r < 9; r++) {
      if (board[r]![c] === ".") continue;
      if (vals.has(board[r]![c]!)) return false;

      vals.add(board[r]![c]!);
    }
  }

  for (let b = 0; b < 9; b++) {
    const vals = new Set<string>();

    let min = Math.floor(b / 3) * 3;
    let cmin = (b % 3) * 3;
    for (let r = min; r < min + 3; r++) {
      for (let c = cmin; c < cmin + 3; c++) {
        if (board[r]![c] === ".") continue;
        if (vals.has(board[r]![c]!)) return false;

        vals.add(board[r]![c]!);
      }
    }
  }

  return true;
}

